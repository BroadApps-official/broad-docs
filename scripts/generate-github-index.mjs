import { writeFile } from "node:fs/promises";

const owner = "BroadApps-official";
const sources = [
  { repository: "broad-core-ios", ref: "1.0.0", label: "BroadCore" },
  { repository: "broad-extensions-ios", ref: "1.0.0", label: "BroadExtensions" },
  { repository: "broad-monetization-ios", ref: "1.0.0", label: "BroadMonetization" },
  { repository: "broad-ui-flows-ios", ref: "1.0.0", label: "BroadUIFlows" },
  { repository: "broad-platform-integration", ref: "main", label: "Integration" },
  { repository: "broad-docs", ref: "main", label: "Docs" },
];

const requestHeaders = {
  Accept: "application/vnd.github+json",
  "User-Agent": "BroadApps-docs-search-index",
  "X-GitHub-Api-Version": "2022-11-28",
};

function includePath(repository, path) {
  if (repository === "broad-docs") {
    return /^(?:README|CONTRIBUTING|CHANGELOG)\.md$/i.test(path) || /^content\/[^/]+\.md$/i.test(path);
  }

  if (repository === "broad-platform-integration") {
    return /^(?:README|README\.dev|CHANGELOG)\.md$/i.test(path)
      || /^Documentation\/.*\.md$/i.test(path)
      || /^AgentChecks\/STATUS\.md$/i.test(path)
      || path === "Compatibility/current.yml";
  }

  return /^(?:README|CHANGELOG)\.md$/i.test(path)
    || /^Documentation\/.*\.md$/i.test(path)
    || /^Examples\/.*\/README\.md$/i.test(path);
}

function titleFromBody(body, path) {
  const heading = body.match(/^#\s+(.+)$/m)?.[1]
    ?.replace(/\[(.*?)\]\([^)]*\)/g, "$1")
    .replace(/[*_`]/g, "")
    .trim();
  if (heading) return heading;
  return path.split("/").at(-1)?.replace(/\.(?:md|yml)$/i, "") ?? path;
}

function descriptionFromBody(body) {
  const cleaned = body
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/<!--([\s\S]*?)-->/g, " ")
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph
      .replace(/^#{1,6}\s+.*$/gm, "")
      .replace(/^\s*[>|-].*$/gm, "")
      .replace(/<[^>]+>/g, " ")
      .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
      .replace(/\[(.*?)\]\([^)]*\)/g, "$1")
      .replace(/[*_`]/g, "")
      .replace(/\s+/g, " ")
      .trim())
    .find((paragraph) => paragraph.length >= 45);

  if (!cleaned) return "Публичный документ BroadApps iOS на GitHub.";
  return cleaned.length > 190 ? `${cleaned.slice(0, 187).trim()}…` : cleaned;
}

function kindFromPath(path) {
  const name = path.split("/").at(-1)?.toLowerCase();
  if (name === "readme.md" || name === "readme.dev.md") return "README";
  if (name === "changelog.md") return "CHANGELOG";
  if (path.endsWith(".yml")) return "CATALOG";
  if (path.startsWith("Examples/")) return "EXAMPLE";
  return "GUIDE";
}

async function fetchText(url) {
  const response = await fetch(url, { headers: requestHeaders });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${url}`);
  return response.text();
}

const documents = [];

for (const source of sources) {
  const treeUrl = `https://api.github.com/repos/${owner}/${source.repository}/git/trees/${encodeURIComponent(source.ref)}?recursive=1`;
  const tree = JSON.parse(await fetchText(treeUrl));
  if (tree.truncated) throw new Error(`GitHub tree is truncated for ${source.repository}@${source.ref}`);

  const paths = tree.tree
    .filter((entry) => entry.type === "blob" && includePath(source.repository, entry.path))
    .map((entry) => entry.path)
    .sort((left, right) => left.localeCompare(right, "en"));

  for (const path of paths) {
    const rawUrl = `https://raw.githubusercontent.com/${owner}/${source.repository}/${source.ref}/${path}`;
    const body = await fetchText(rawUrl);
    documents.push({
      id: `${source.repository}:${path}`,
      repository: source.repository,
      repositoryLabel: source.label,
      ref: source.ref,
      path,
      kind: kindFromPath(path),
      title: titleFromBody(body, path),
      description: descriptionFromBody(body),
      href: `https://github.com/${owner}/${source.repository}/blob/${source.ref}/${path}`,
      body,
    });
  }
}

documents.sort((left, right) => left.repository.localeCompare(right.repository, "en") || left.path.localeCompare(right.path, "en"));

const output = `// Generated by scripts/generate-github-index.mjs. Do not edit manually.\n\n`
  + `export type GitHubDocument = {\n`
  + `  id: string;\n  repository: string;\n  repositoryLabel: string;\n  ref: string;\n  path: string;\n`
  + `  kind: "README" | "CHANGELOG" | "CATALOG" | "EXAMPLE" | "GUIDE";\n`
  + `  title: string;\n  description: string;\n  href: string;\n  body: string;\n};\n\n`
  + `export const githubDocuments: GitHubDocument[] = ${JSON.stringify(documents, null, 2)};\n`;

await writeFile(new URL("../lib/github-docs.generated.ts", import.meta.url), output);
console.log(`GitHub search index generated: ${documents.length} documents from ${sources.length} repositories.`);
